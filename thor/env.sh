# Layout of the Thor port.  Source this file from other scripts; nothing else names a machine.
#
#   THOR_ROOT/src/UniXNU-thor      this repository: the port itself (kernel patches, driver patches, recipe, tools, records)
#   THOR_ROOT/src/UniXNU           upstream build system
#   THOR_ROOT/src/UniXNU-pong      device repository: scripts, kits, the driver repositories with Thor's changes, pinned reference sources
#   THOR_ROOT/inputs/              what builds read: decrypted IPSW components, signed libraries, private firmware inputs, tools
#   THOR_ROOT/work/<release>/      a working copy, generated by thor/bootstrap.py: disposable
#   THOR_ROOT/images/<release>/    boot images with their records
#   THOR_ROOT/logs/<release>/      logs collected from the phone
#   THOR_ROOT/archive/             what is kept but no longer used
# This file is <root>/src/UniXNU-thor/thor/env.sh: the root is three levels up.
THOR_ROOT=${THOR_ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd -P)}
test -d "$THOR_ROOT/src/UniXNU-pong/refer" && test -d "$THOR_ROOT/inputs" || { echo "thor/env.sh: $THOR_ROOT does not hold src/UniXNU-pong and inputs/" >&2; return 1 2>/dev/null || exit 1; }
export THOR_ROOT
export THOR_REPO=$THOR_ROOT/src/UniXNU-thor
export THOR_PONG=$THOR_ROOT/src/UniXNU-pong
export THOR_INPUTS=$THOR_ROOT/inputs
export THOR_WORK=$THOR_ROOT/work
export THOR_IMAGES=$THOR_ROOT/images
export THOR_LOGS=$THOR_ROOT/logs
export THOR_PY=${THOR_PY:-/opt/homebrew/bin/python3.13}
export THOR_JOBS=${THOR_JOBS:-9}

# Inputs that the device repository's own scripts look for; their defaults name the upstream author's volumes.
export PONG_INPUTS=$THOR_INPUTS
export PONG_WIFI_SOURCE=$THOR_PONG/refer/ipados18/linux-7.0.14
export PONG_SHENG_ROOT=$THOR_PONG/refer/ipados18/UniXNU-sheng
export PONG_LLVM_NM=${PONG_LLVM_NM:-$(xcrun --find llvm-nm)}
export PONG_LLVM_OBJCOPY=${PONG_LLVM_OBJCOPY:-/opt/homebrew/opt/llvm/bin/llvm-objcopy}
export PONG_TOOLS=$THOR_INPUTS/tools/platform-tools      # fastboot and adb
export THOR_SERIAL=${THOR_SERIAL:-}                      # the phone's fastboot serial number comes from the environment
